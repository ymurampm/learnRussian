        # Ensure cloze exists if collocation_ru exists
        if b.get('collocation_ru') and not b.get('collocation_cloze'):
            cw = clean_w.split('/')[0] if '/' in clean_w else clean_w
            if cw in b['collocation_ru'].lower():
                b['collocation_cloze'] = re.sub(re.escape(cw), '[ ❓ ]', b['collocation_ru'], flags=re.I)
            else:
                words = b['collocation_ru'].split()
                if len(words) > 1:
                    b['collocation_cloze'] = '[ ❓ ] ' + ' '.join(words[1:])
                else:
                    b['collocation_cloze'] = '[ ❓ ]'

