def main():
    import sys
    if hasattr(sys.stdout, 'reconfigure'):
        sys.stdout.reconfigure(encoding='utf-8')
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    try:
        from populate_days_21_to_30_evening import EVENING_PARAGRAPHS_DATA
        for d in DAYS_26_TO_30:
            d_idx = d.get('day_index')
            if d_idx in EVENING_PARAGRAPHS_DATA:
                paras = EVENING_PARAGRAPHS_DATA[d_idx]
                d.setdefault('sessions', {}).setdefault('evening', {})['paragraphs'] = paras
                d['sessions']['evening']['audio_paragraphs'] = paras
    except Exception as e:
        print(f"Warning: could not merge evening paragraphs: {e}")

    from validate_curriculum import validate_catalog_list

    valid, summary = validate_catalog_list(DAYS_26_TO_30)
    print(f"Days 26-30 Solvability & Integrity Validation:")
    print(f"  Valid: {valid}")
    print(f"  Total Days: {summary['total_days']}")
    print(f"  Total Questions: {summary['total_questions']}")
    print(f"  Errors: {summary['total_errors']}")
    print(f"  Warnings: {summary['total_warnings']}")

    if not valid:
        print("❌ ERRORS:")
        for err in summary['errors']:
            print(f"  • {err}")
        return 1

    # Output to catalog if requested
    if len(sys.argv) > 1 and sys.argv[1] == '--apply':
        cat_p = os.path.join(ROOT_DIR, 'data', 'curriculum_catalog.json')
        buf_p = os.path.join(ROOT_DIR, 'data', 'lesson_buffer.json')

        with open(cat_p, 'r', encoding='utf-8') as f:
            catalog = json.load(f)
        with open(buf_p, 'r', encoding='utf-8') as f:
            buffer = json.load(f)

        existing_cat = {d['day_index'] for d in catalog}
        existing_buf = {d['day_index'] for d in buffer}

        added_cat = 0
        added_buf = 0
        for d in DAYS_26_TO_30:
            idx = d['day_index']
            if idx not in existing_cat:
                catalog.append(d)
                added_cat += 1
            if idx not in existing_buf:
                buffer.append(d)
                added_buf += 1

        catalog.sort(key=lambda x: x['day_index'])
        buffer.sort(key=lambda x: x['day_index'])

        with open(cat_p, 'w', encoding='utf-8') as f:
            json.dump(catalog, f, ensure_ascii=False, indent=2)
        with open(buf_p, 'w', encoding='utf-8') as f:
            json.dump(buffer, f, ensure_ascii=False, indent=2)

        print(f"Applied successfully: +{added_cat} to catalog, +{added_buf} to buffer.")

    return 0

if __name__ == '__main__':
    sys.exit(main())
