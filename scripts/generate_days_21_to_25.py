def main():
    # Merge rich evening paragraphs
    sys.path.insert(0, os.path.join(ROOT_DIR, 'scripts'))
    try:
        from populate_days_21_to_30_evening import EVENING_PARAGRAPHS_DATA
        for d in DAYS_21_TO_25:
            d_idx = d.get('day_index')
            if d_idx in EVENING_PARAGRAPHS_DATA:
                paras = EVENING_PARAGRAPHS_DATA[d_idx]
                d.setdefault('sessions', {}).setdefault('evening', {})['paragraphs'] = paras
                d['sessions']['evening']['audio_paragraphs'] = paras
    except Exception as e:
        print(f"Warning: could not merge evening paragraphs: {e}")

    # Load catalog
    catalog_path = os.path.join(ROOT_DIR, 'data', 'curriculum_catalog.json')
    with open(catalog_path, 'r', encoding='utf-8') as f:
        catalog = json.load(f)

    # Filter out any existing days >= 21
    catalog = [d for d in catalog if d.get('day_index') < 21]

    # Append new days 21-25
    catalog.extend(DAYS_21_TO_25)
    catalog.sort(key=lambda d: d.get('day_index', 0))

    # Save to curriculum_catalog.json
    with open(catalog_path, 'w', encoding='utf-8') as f:
        json.dump(catalog, f, ensure_ascii=False, indent=2)
    print(f"Saved {len(catalog)} days to curriculum_catalog.json (Days 1 to {catalog[-1]['day_index']}).")

    # Now replenish lesson_buffer.json via batch_generator
    sys.path.insert(0, os.path.join(ROOT_DIR, 'scripts'))
    import batch_generator
    rep_res = batch_generator.replenish_buffer_if_needed(target_unconsumed=5)
    print(f"Buffer replenish result: {rep_res}")

if __name__ == '__main__':
    main()
